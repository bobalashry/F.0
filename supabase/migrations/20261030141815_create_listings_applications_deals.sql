/*
# Create listings, applications, deals and deal history

Plain-English summary:
- Owners publish "Sell For Me" listings with a price, location, commission and commission terms.
- Workers apply to active listings with a short message.
- Owners accept or reject applications. Accepting an application creates a deal with a unique deal number that stores the agreed commission and terms.
- Every deal change is recorded in a deal history.
- Only the owner who published a listing can edit, pause, close or delete it. Only the worker can withdraw their own application.

## 1. New tables
- `listings`: id, owner_id, category, title, description, price (EGP), location, commission_type ('percentage' or 'fixed'), commission_value, commission_terms, duration_days, status ('active', 'paused', 'closed'), timestamps.
- `applications`: id, listing_id, worker_id, message, status ('pending', 'accepted', 'rejected', 'withdrawn'), timestamps. One application per worker per listing.
- `deals`: id, deal_number (unique), listing_id, application_id (unique), owner_id, worker_id, snapshot of the listing title, price and commission terms at agreement time, status ('active', 'completed'), timestamps.
- `deal_events`: id, deal_id, actor_id, event_type, note, created_at. Append-only history.

## 2. Security
- Row level security enabled on all four tables.
- Listings: signed-in users see active listings and their own listings. Only owners (account type 'owner') can create listings, and only for themselves.
- Applications: workers see their own; owners see applications for their listings. Only workers (account type 'worker') can apply, and not to their own listings.
- Deals and deal history: visible only to the two parties.
- Deals, deal history, and application decisions are written only through the server-side functions in the next migration, never directly by clients.
- Clients cannot change ownership, worker identity, snapshots, deal numbers or account types.

## 3. Important notes
1. Deleting a listing is blocked when it has deals, to keep the agreement record intact.
2. Deal numbers are generated by the database.
*/

CREATE TABLE IF NOT EXISTS public.listings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id uuid NOT NULL DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE CASCADE,
  category text NOT NULL CHECK (category IN ('cars', 'real_estate', 'electronics', 'furniture', 'commercial', 'services')),
  title text NOT NULL CHECK (char_length(title) BETWEEN 3 AND 120),
  description text NOT NULL CHECK (char_length(description) BETWEEN 10 AND 4000),
  price numeric(14, 2) NOT NULL CHECK (price >= 0),
  location text NOT NULL CHECK (char_length(location) BETWEEN 2 AND 120),
  commission_type text NOT NULL CHECK (commission_type IN ('percentage', 'fixed')),
  commission_value numeric(14, 2) NOT NULL CHECK (commission_value >= 0),
  commission_terms text NOT NULL CHECK (char_length(commission_terms) BETWEEN 5 AND 1000),
  duration_days integer NOT NULL CHECK (duration_days BETWEEN 1 AND 365),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'closed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT listings_percentage_range CHECK (commission_type <> 'percentage' OR commission_value <= 100)
);

CREATE INDEX IF NOT EXISTS listings_owner_idx ON public.listings (owner_id);
CREATE INDEX IF NOT EXISTS listings_status_category_idx ON public.listings (status, category);

ALTER TABLE public.listings ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, DELETE ON public.listings TO authenticated;
GRANT UPDATE (category, title, description, price, location, commission_type, commission_value, commission_terms, duration_days, status) ON public.listings TO authenticated;

DROP POLICY IF EXISTS "select_visible_listings" ON public.listings;
CREATE POLICY "select_visible_listings" ON public.listings FOR SELECT
  TO authenticated USING (status = 'active' OR owner_id = auth.uid());

DROP POLICY IF EXISTS "insert_own_listing" ON public.listings;
CREATE POLICY "insert_own_listing" ON public.listings FOR INSERT
  TO authenticated WITH CHECK (
    owner_id = auth.uid()
    AND status IN ('active', 'paused')
    AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.account_type = 'owner')
  );

DROP POLICY IF EXISTS "update_own_listing" ON public.listings;
CREATE POLICY "update_own_listing" ON public.listings FOR UPDATE
  TO authenticated USING (owner_id = auth.uid())
  WITH CHECK (owner_id = auth.uid() AND status IN ('active', 'paused', 'closed'));

DROP POLICY IF EXISTS "delete_own_listing" ON public.listings;
CREATE POLICY "delete_own_listing" ON public.listings FOR DELETE
  TO authenticated USING (owner_id = auth.uid());

DROP TRIGGER IF EXISTS listings_set_updated_at ON public.listings;
CREATE TRIGGER listings_set_updated_at BEFORE UPDATE ON public.listings
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE IF NOT EXISTS public.applications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  listing_id uuid NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
  worker_id uuid NOT NULL DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE CASCADE,
  message text NOT NULL CHECK (char_length(message) BETWEEN 10 AND 1000),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'rejected', 'withdrawn')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT applications_one_per_worker UNIQUE (listing_id, worker_id)
);

CREATE INDEX IF NOT EXISTS applications_worker_idx ON public.applications (worker_id);

ALTER TABLE public.applications ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.applications TO authenticated;
GRANT INSERT (listing_id, message) ON public.applications TO authenticated;

DROP POLICY IF EXISTS "select_related_applications" ON public.applications;
CREATE POLICY "select_related_applications" ON public.applications FOR SELECT
  TO authenticated USING (
    worker_id = auth.uid()
    OR EXISTS (SELECT 1 FROM public.listings l WHERE l.id = applications.listing_id AND l.owner_id = auth.uid())
  );

DROP POLICY IF EXISTS "insert_own_application" ON public.applications;
CREATE POLICY "insert_own_application" ON public.applications FOR INSERT
  TO authenticated WITH CHECK (
    worker_id = auth.uid()
    AND status = 'pending'
    AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.account_type = 'worker')
    AND EXISTS (
      SELECT 1 FROM public.listings l
      WHERE l.id = listing_id AND l.status = 'active' AND l.owner_id <> auth.uid()
    )
  );

DROP TRIGGER IF EXISTS applications_set_updated_at ON public.applications;
CREATE TRIGGER applications_set_updated_at BEFORE UPDATE ON public.applications
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE IF NOT EXISTS public.deals (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  deal_number text NOT NULL UNIQUE DEFAULT ('DL-' || to_char(now(), 'YYMMDD') || '-' || upper(substr(md5(gen_random_uuid()::text), 1, 6))),
  listing_id uuid NOT NULL REFERENCES public.listings(id) ON DELETE RESTRICT,
  application_id uuid NOT NULL UNIQUE REFERENCES public.applications(id) ON DELETE RESTRICT,
  owner_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  worker_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  listing_title text NOT NULL,
  listing_price numeric(14, 2) NOT NULL CHECK (listing_price >= 0),
  commission_type text NOT NULL CHECK (commission_type IN ('percentage', 'fixed')),
  commission_value numeric(14, 2) NOT NULL CHECK (commission_value >= 0),
  commission_terms text NOT NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CONSTRAINT deals_parties_differ CHECK (owner_id <> worker_id)
);

CREATE INDEX IF NOT EXISTS deals_owner_idx ON public.deals (owner_id);
CREATE INDEX IF NOT EXISTS deals_worker_idx ON public.deals (worker_id);

ALTER TABLE public.deals ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.deals TO authenticated;

DROP POLICY IF EXISTS "select_own_deals" ON public.deals;
CREATE POLICY "select_own_deals" ON public.deals FOR SELECT
  TO authenticated USING (owner_id = auth.uid() OR worker_id = auth.uid());

CREATE TABLE IF NOT EXISTS public.deal_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  deal_id uuid NOT NULL REFERENCES public.deals(id) ON DELETE CASCADE,
  actor_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
  event_type text NOT NULL CHECK (event_type IN ('created', 'completed')),
  note text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS deal_events_deal_idx ON public.deal_events (deal_id);

ALTER TABLE public.deal_events ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.deal_events TO authenticated;

DROP POLICY IF EXISTS "select_own_deal_events" ON public.deal_events;
CREATE POLICY "select_own_deal_events" ON public.deal_events FOR SELECT
  TO authenticated USING (
    EXISTS (
      SELECT 1 FROM public.deals d
      WHERE d.id = deal_events.deal_id AND (d.owner_id = auth.uid() OR d.worker_id = auth.uid())
    )
  );
